const ALL_PRODUCTS = [
  ...SEED_SKINCARE_PRODUCTS,
  ...SEED_TOYS_PRODUCTS,
  ...SEED_JOURNALS_PRODUCTS,
];

async function seed() {
  console.log(`Upserting ${ALL_PRODUCTS.length} products into Supabase...`);
  for (const item of ALL_PRODUCTS) {
    const { data, error } = await supabase.from('products').upsert(item, { onConflict: 'id' }).select();
    if (error) {
      console.error(`Error inserting ${item.id}:`, error);
    } else {
      console.log(`Successfully upserted: ${item.id} - ${item.name}`);
    }
  }
  console.log('Seeding finished!');
}

seed().catch(console.error);
